import test from 'node:test';
import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {readFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
const {chromium} = createRequire(import.meta.url)('playwright');

test('custom selects: keyboard, search, forms, lifecycle, safety and mobile', async () => {
  const server = createServer(async (request, response) => {
    const filename = request.url.endsWith('.css') ? 'styles.css' : 'index.js';
    response.setHeader('Content-Type', filename.endsWith('.css') ? 'text/css' : 'text/javascript');
    response.setHeader('Access-Control-Allow-Origin', '*');
    response.end(await readFile(new URL(`../shared/components/custom-select/${filename}`, import.meta.url)));
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  let browser;
  try {
    browser = await chromium.launch({headless: true, executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox']});
    const page = await browser.newPage({viewport: {width: 1100, height: 800}});
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    const base = `http://127.0.0.1:${server.address().port}`;
    await page.setContent(`<link rel="stylesheet" href="${base}/styles.css"><main id="app"><form><label>Categoria<select name="category" required><option value="">Escolha</option><option value="fruit">Frutas</option><option disabled>Indisponível</option><optgroup label="Mercearia"><option value="rice">Arroz</option><option value="beans">Feijão</option></optgroup></select></label><button type="submit">Salvar</button><button type="reset">Limpar</button></form><button id="outside">Fora</button><div id="dynamic"></div></main>`);
    await page.evaluate(async base => {
      const {installCustomSelects} = await import(`${base}/index.js`);
      window.manager = installCustomSelects(document.querySelector('#app'));
      window.events = [];
      document.querySelector('select').addEventListener('change', event => window.events.push(event.target.value));
      document.querySelector('form').onsubmit = event => event.preventDefault();
    }, base);
    const combo = page.getByRole('combobox', {name: 'Categoria', exact: true});
    assert.equal(await page.locator('select').isVisible(), false);
    await page.getByRole('button', {name: 'Salvar', exact: true}).click();
    assert.equal(await combo.getAttribute('aria-invalid'), 'true');
    assert.equal(await combo.evaluate(node => node === document.activeElement), true);
    await combo.press('ArrowDown');
    await combo.press('ArrowDown');
    await combo.press('Enter');
    assert.equal(await page.locator('select').inputValue(), 'fruit');
    assert.equal(await combo.textContent(), 'Frutas⌄');
    assert.deepEqual(await page.evaluate(() => window.events), ['fruit']);
    assert.equal(await page.evaluate(() => new FormData(document.querySelector('form')).get('category')), 'fruit');
    await combo.click(); await combo.press('End'); await combo.press('Enter');
    assert.equal(await page.locator('select').inputValue(), 'beans');
    await combo.click(); await combo.press('Home'); await combo.press('ArrowDown'); await combo.press('ArrowDown'); await combo.press('Enter');
    assert.equal(await page.locator('select').inputValue(), 'rice', 'disabled option is skipped');
    await combo.click(); await combo.press('Escape');
    assert.equal(await combo.getAttribute('aria-expanded'), 'false');
    assert.equal(await combo.evaluate(node => node === document.activeElement), true);
    await combo.click(); await page.locator('#outside').click();
    assert.equal(await combo.getAttribute('aria-expanded'), 'false');
    await page.evaluate(() => { document.querySelector('select').value = 'beans'; });
    assert.equal(await combo.textContent(), 'Feijão⌄');
    await page.getByRole('button', {name: 'Limpar', exact: true}).click();
    await page.waitForFunction(() => document.querySelector('.custom-select-value').textContent === 'Escolha');
    await page.evaluate(() => { document.querySelector('select').disabled = true; });
    await page.waitForFunction(() => document.querySelector('.custom-select-trigger').disabled);
    await page.evaluate(() => { document.querySelector('select').disabled = false; document.querySelector('select').append(new Option('<img src=x onerror=alert(1)>', 'safe')); });
    await combo.click();
    assert.equal(await page.getByRole('option', {name: '<img src=x onerror=alert(1)>'}).count(), 1);
    assert.equal(await page.locator('.custom-select-options img').count(), 0);
    await combo.press('Escape');
    await page.evaluate(() => { document.querySelector('#dynamic').innerHTML = '<label>Estado<select name="state">'+Array.from({length: 20}, (_, i) => `<option value="${i}">Estado ${i}</option>`).join('')+'</select></label>'; });
    const states = page.getByRole('combobox', {name: 'Estado', exact: true});
    await states.click();
    const search = page.getByRole('combobox', {name: 'Buscar opção', exact: true});
    await search.fill('Estado 19');
    assert.equal(await page.getByRole('option').count(), 1);
    await search.press('Enter');
    assert.equal(await page.locator('select[name=state]').inputValue(), '19');
    await states.click(); await search.fill('não existe');
    assert.equal(await page.getByText('Nenhuma opção encontrada.').isVisible(), true);
    await search.press('Escape');
    await page.setViewportSize({width: 390, height: 844});
    await states.click();
    const bounds = await page.locator('.custom-select-popup:not([hidden])').boundingBox();
    assert(bounds.x >= 0 && bounds.x + bounds.width <= 390 && bounds.y >= 0 && bounds.y + bounds.height <= 844);
    assert(await page.getByRole('button', {name: 'Fechar', exact: true}).isVisible());
    await page.getByRole('button', {name: 'Fechar', exact: true}).click();
    assert.equal(await states.evaluate(node => node === document.activeElement), true);
    await page.evaluate(() => { document.querySelector('#dynamic').replaceChildren(); });
    await page.waitForFunction(() => document.querySelectorAll('.custom-select-popup').length === 1);
    assert.equal(await page.locator('.custom-select-popup').count(), 1, 'removed routes clean up their portals');
    assert.deepEqual(errors, []);
    await page.evaluate(() => window.manager.destroy());
    assert.equal(await page.locator('.custom-select-popup').count(), 0);
    assert.equal(await page.locator('select').isVisible(), true, 'destroy restores original native markup');
  } finally { await browser?.close(); await new Promise(resolve => server.close(resolve)); }
});
